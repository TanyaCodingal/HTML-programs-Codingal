#Create an empty list
l1=[]
print("List 1 has",len(l1),"characters.")

#Create a list with elements
l2=["Emma",0.23,12,True]
print("List 2 has",len(l2),"characters :",l2)

#Printing a new list multiple times using '*'
l3=["Anika",12,87.9]*3
print("List 3 :",l3)

#Reversing a list
l4=["Hello",0,0.5]
print("List 4 :",l4)
print("Reversed list :",l4[::-1])